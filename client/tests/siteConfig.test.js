import test from 'node:test';
import assert from 'node:assert';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { injectSiteUrl, SITE_URL_PLACEHOLDER } from '../seo/siteSeoPlugin.js';

const clientDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoDir = path.resolve(clientDir, '..');
const publicDir = path.join(clientDir, 'public');
const read = (...parts) => fs.readFileSync(path.join(...parts));

const pngSize = (buffer) => {
  assert.ok(
    buffer.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])),
    'PNG signature'
  );
  return [buffer.readUInt32BE(16), buffer.readUInt32BE(20)];
};

test('vercel.json: feed rewrites precede the API and SPA catch-alls and hit the same backend', () => {
  const config = JSON.parse(read(repoDir, 'vercel.json'));
  const sources = config.rewrites.map((r) => r.source);
  const catchAll = sources.indexOf('/(.*)');
  const apiIndex = sources.indexOf('/api/(.*)');
  assert.strictEqual(catchAll, sources.length - 1, 'SPA catch-all is last');
  for (const feed of ['/sitemap.xml', '/rss.xml']) {
    const index = sources.indexOf(feed);
    assert.ok(
      index >= 0 && index < apiIndex && index < catchAll,
      `${feed} rewrite before catch-alls`
    );
  }

  const backend = new URL(config.rewrites[apiIndex].destination.replace('$1', '')).origin;
  const byFeed = Object.fromEntries(config.rewrites.map((r) => [r.source, r.destination]));
  // Verified backend routes (server/src/routes/seo.routes.js mounted at the root in app.js)
  assert.strictEqual(byFeed['/sitemap.xml'], `${backend}/sitemap.xml`);
  assert.strictEqual(byFeed['/rss.xml'], `${backend}/rss.xml`);
});

test('vercel.json: private areas send X-Robots-Tag noindex', () => {
  const config = JSON.parse(read(repoDir, 'vercel.json'));
  for (const source of ['/admin', '/admin/(.*)', '/login', '/auth/(.*)']) {
    const rule = config.headers.find((h) => h.source === source);
    assert.ok(rule, source);
    assert.deepStrictEqual(rule.headers, [{ key: 'X-Robots-Tag', value: 'noindex, nofollow' }]);
  }
});

test('no static sitemap/robots in public/ can shadow the dynamic feed or build output', () => {
  assert.ok(!fs.existsSync(path.join(publicDir, 'sitemap.xml')), 'static mock sitemap removed');
  assert.ok(
    !fs.existsSync(path.join(publicDir, 'robots.txt')),
    'robots.txt is generated by the build'
  );
  assert.ok(!fs.existsSync(path.join(publicDir, 'rss.xml')));
});

test('index.html: build-time site URL, absolute social image, favicon links, no static canonical', () => {
  const source = read(clientDir, 'index.html').toString();
  assert.ok(source.includes(SITE_URL_PLACEHOLDER));
  const html = injectSiteUrl(source, 'https://example.test/');
  assert.ok(!html.includes(SITE_URL_PLACEHOLDER), 'placeholder fully replaced');
  assert.match(
    html,
    /<meta property="og:image" content="https:\/\/example\.test\/og-default\.png"/
  );
  assert.match(
    html,
    /<meta name="twitter:image" content="https:\/\/example\.test\/og-default\.png"/
  );
  assert.match(html, /<meta name="twitter:card" content="summary_large_image"/);
  assert.match(html, /<link rel="icon" href="\/favicon\.svg" type="image\/svg\+xml"/);
  assert.match(html, /<link rel="icon" href="\/favicon\.ico"/);
  assert.match(html, /<link rel="apple-touch-icon" href="\/apple-touch-icon\.png"/);
  assert.match(html, /href="https:\/\/example\.test\/rss\.xml"/);
  assert.ok(!/rel="canonical"/.test(html), 'no static canonical (served for every route)');
  assert.ok(!/property="og:url"/.test(html), 'no static og:url');
  assert.ok(!/unsplash/i.test(html));
  assert.strictEqual((html.match(/<title>/g) || []).length, 1);
  assert.strictEqual(
    injectSiteUrl(source, undefined).includes('https://yashjha.vercel.app/og-default.png'),
    true
  );
});

test('brand assets exist with the expected formats and sizes', () => {
  assert.deepStrictEqual(pngSize(read(publicDir, 'og-default.png')), [1200, 630]);
  assert.deepStrictEqual(pngSize(read(publicDir, 'favicon-32.png')), [32, 32]);
  assert.deepStrictEqual(pngSize(read(publicDir, 'apple-touch-icon.png')), [180, 180]);
  assert.deepStrictEqual(pngSize(read(publicDir, 'icon-512.png')), [512, 512]);

  const ico = read(publicDir, 'favicon.ico');
  assert.strictEqual(ico.readUInt16LE(2), 1, 'ICO type');
  assert.strictEqual(ico.readUInt16LE(4), 1, 'one image');
  assert.strictEqual(ico.readUInt8(6), 32, '32px');
  assert.deepStrictEqual(pngSize(ico.subarray(ico.readUInt32LE(18))), [32, 32], 'embedded PNG');

  const svg = read(publicDir, 'favicon.svg').toString();
  assert.match(svg, /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 64 64"/);
  assert.ok(!/<text/.test(svg), 'monogram is drawn with paths, no font dependency');
});

test('no source file references the unresolved custom domains', () => {
  const offenders = [];
  const scan = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (['node_modules', 'dist', '.git'].includes(entry.name)) continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) scan(full);
      else if (/\.(jsx?|mjs|html|json|txt|xml)$/.test(entry.name)) {
        if (/portfolio\.yashjha024\.com|yashjhai\.com/.test(fs.readFileSync(full, 'utf8')))
          offenders.push(full);
      }
    }
  };
  scan(path.join(clientDir, 'src'));
  scan(path.join(clientDir, 'public'));
  scan(path.join(repoDir, 'server', 'src'));
  for (const file of ['vercel.json', path.join('client', 'index.html')]) {
    if (
      /portfolio\.yashjha024\.com|yashjhai\.com/.test(
        fs.readFileSync(path.join(repoDir, file), 'utf8')
      )
    )
      offenders.push(file);
  }
  assert.deepStrictEqual(offenders, []);
});
